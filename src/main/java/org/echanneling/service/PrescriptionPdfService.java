package org.echanneling.service;

import org.apache.pdfbox.pdmodel.PDDocument;
import org.apache.pdfbox.pdmodel.PDPage;
import org.apache.pdfbox.pdmodel.PDPageContentStream;
import org.apache.pdfbox.pdmodel.common.PDRectangle;
import org.apache.pdfbox.pdmodel.font.PDType1Font;
import org.apache.pdfbox.pdmodel.font.Standard14Fonts;
import org.echanneling.model.Prescription;
import org.echanneling.model.PrescriptionItem;
import org.springframework.stereotype.Service;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.time.format.DateTimeFormatter;

@Service
public class PrescriptionPdfService {
    private final PrescriptionService prescriptionService;

    public PrescriptionPdfService(PrescriptionService prescriptionService) {
        this.prescriptionService = prescriptionService;
    }

    public byte[] generate(int prescriptionId) {
        Prescription p = prescriptionService.getPrescriptionById(prescriptionId);
        try (PDDocument document = new PDDocument(); ByteArrayOutputStream out = new ByteArrayOutputStream()) {
            PDPage page = new PDPage(PDRectangle.A4);
            document.addPage(page);
            PDType1Font normal = new PDType1Font(Standard14Fonts.FontName.HELVETICA);
            PDType1Font bold = new PDType1Font(Standard14Fonts.FontName.HELVETICA_BOLD);
            try (PDPageContentStream c = new PDPageContentStream(document, page)) {
                float y = 790;
                text(c, bold, 22, 50, y, "MediConnect - Digital Prescription"); y -= 28;
                text(c, normal, 11, 50, y, "Prescription ID: #" + p.getPrescriptionId()); y -= 18;
                text(c, normal, 11, 50, y, "Appointment ID: #" + p.getAppointmentId()); y -= 18;
                text(c, normal, 11, 50, y, "Doctor ID: #" + p.getDoctorId()); y -= 18;
                if (p.getCreatedAt() != null) {
                    text(c, normal, 11, 50, y, "Issued: " + p.getCreatedAt().format(DateTimeFormatter.ofPattern("dd MMM yyyy, hh:mm a"))); y -= 28;
                }
                c.moveTo(50, y); c.lineTo(545, y); c.stroke(); y -= 28;
                text(c, bold, 12, 50, y, "Medicines"); y -= 24;
                int n = 1;
                for (PrescriptionItem i : p.getItems()) {
                    if (y < 100) break;
                    text(c, bold, 11, 55, y, n + ". " + safe(i.getMedicineName())); y -= 17;
                    text(c, normal, 10, 70, y, "Dosage: " + safe(i.getDosage()) + "   |   Frequency: " + safe(i.getFrequency())); y -= 15;
                    text(c, normal, 10, 70, y, "Duration: " + safe(i.getDuration())); y -= 15;
                    if (i.getInstructions() != null && !i.getInstructions().isBlank()) {
                        text(c, normal, 10, 70, y, "Instructions: " + safe(i.getInstructions())); y -= 15;
                    }
                    y -= 12; n++;
                }
                text(c, normal, 9, 50, 55, "This digital prescription was generated by MediConnect.");
            }
            document.save(out);
            return out.toByteArray();
        } catch (IOException e) {
            throw new RuntimeException("Failed to generate prescription PDF", e);
        }
    }

    private String safe(String s) { return s == null ? "-" : s.replaceAll("[^\\x20-\\x7E]", ""); }
    private void text(PDPageContentStream c, PDType1Font f, float size, float x, float y, String value) throws IOException {
        c.beginText(); c.setFont(f, size); c.newLineAtOffset(x, y); c.showText(safe(value)); c.endText();
    }
}
